/// Birlik yorlig'i — serverdan «kg / dona / l / porsiya» keladi, ekranda
/// foydalanuvchi tilida chiqadi (ruscha ekranda «kg», «dona» qolib ketardi).
/// Noma'lum birlik o'zicha qaytadi.
String unitLabel(String unit, Tr tr) {
  switch (unit.trim().toLowerCase()) {
    case 'kg': case 'кг': return tr('u_kg');
    case 'dona': case 'шт': case 'pcs': case 'pc': return tr('u_dona');
    case 'l': case 'л': case 'litr': case 'ltr': return tr('u_l');
    case 'porsiya': case 'порц': case 'порц.': case 'portion': return tr('u_porsiya');
    default: return unit;
  }
}
