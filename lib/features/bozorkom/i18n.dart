const kLocales = ['uz', 'ru', 'en'];

/// Tanlangan til — SharedPreferences'da saqlanadi.
final localeProvider = StateNotifierProvider<LocaleCtl, String>((ref) {
  final prefs = ref.watch(sharedPreferencesProvider);
  return LocaleCtl(prefs.getString('bozor_locale') ?? 'uz', (v) => prefs.setString('bozor_locale', v));
});

class LocaleCtl extends StateNotifier<String> {
  LocaleCtl(super.initial, this._save);
  final Future<bool> Function(String) _save;
  void set(String code) {
    if (!kLocales.contains(code)) return;
    state = code;
    _save(code);
  }
}

typedef Tr = String Function(String key, [Map<String, String>? args]);

/// `tr('key')` — joriy tilda matn. Kalit topilmasa o'zbekcha, u ham bo'lmasa kalit.
final trProvider = Provider<Tr>((ref) {
  final loc = ref.watch(localeProvider);
  return (key, [args]) {
    var s = _strings[loc]?[key] ?? _strings['uz']?[key] ?? key;
    args?.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  };
});

